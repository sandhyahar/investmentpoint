<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * Dark mode for the public website: reads the CSS of every public page (the <style> blocks and
 * style partials in resources/views, admin and e-mails left out) and writes public/css/dark.css
 * with the same rules re-coloured for a dark background, all under html[data-theme="dark"].
 *
 * Light backgrounds become dark navy surfaces, dark text becomes light, light borders become
 * dark lines. Colours that already work on dark (navy panels, gold / green / red accents, white
 * text) are left alone. Re-run after changing page colours:  php artisan theme:dark
 */
class BuildDarkTheme extends Command
{
    protected $signature = 'theme:dark';

    protected $description = 'Build public/css/dark.css (dark mode) from the public pages\' CSS';

    private const PREFIX = 'html[data-theme="dark"]';

    /** CSS custom properties (--name => value), so var(--text) etc. can be re-coloured too */
    private array $vars = [];

    public function handle(): int
    {
        $sources = $this->collectCss();

        $trees = [];
        foreach ($sources as $file => $css) {
            $trees[$file] = $this->parse($css);
        }
        foreach ($trees as $tree) {
            $this->collectVars($tree);
        }

        $out = [];
        foreach ($trees as $file => $tree) {
            $block = $this->emit($tree, '', $file === 'layouts/app.blade.php');
            if (trim($block) !== '') {
                $out[] = "/* " . $file . " */\n" . $block;
            }
        }

        $css = "/* Dark mode - generated by `php artisan theme:dark` from the page styles. Do not edit by hand:\n"
            . "   change the page CSS (or the hand-made part at the end of BuildDarkTheme) and run the command again. */\n"
            . implode("\n", $out) . "\n" . $this->manual();

        File::ensureDirectoryExists(public_path('css'));
        File::put(public_path('css/dark.css'), $css);
        $this->info(sprintf('public/css/dark.css written (%d files read, %.1f KB).', count($sources), strlen($css) / 1024));

        return self::SUCCESS;
    }

    /* ------------------------------------------------------------------ reading the CSS */

    /** file => raw CSS for every public view that has styles */
    private function collectCss(): array
    {
        $root = resource_path('views');
        $out = [];
        foreach (File::allFiles($root) as $f) {
            $rel = str_replace('\\', '/', $f->getRelativePathname());
            if (!str_ends_with($rel, '.blade.php') || preg_match('#^(admin|emails)/#', $rel)) {
                continue;
            }
            $src = File::get($f->getPathname());
            $src = preg_replace('/\{\{--.*?--\}\}/s', '', $src);
            $parts = [];

            if (preg_match_all('#<style[^>]*>(.*?)</style>#si', $src, $m)) {
                $parts = array_merge($parts, $m[1]);
            }
            // Raw CSS in @section('extra-css') (layouts.app prints it inside its own <style>)
            if (preg_match_all("#@section\\('extra-css'\\)(.*?)@endsection#s", $src, $m)) {
                foreach ($m[1] as $section) {
                    if (stripos($section, '<style') === false) {
                        $parts[] = $section;
                    }
                }
            }
            // Pure-CSS partials (e.g. partials/legal-styles), included inside a <style> elsewhere
            if (!$parts && str_contains(basename($rel), 'styles') && stripos($src, '<style') === false) {
                $parts[] = $src;
            }

            $css = $this->stripBlade(implode("\n", $parts));
            if (trim($css) !== '') {
                $out[$rel] = $css;
            }
        }
        ksort($out);
        // The layout first, so its rules come before the page rules (same order as on the page)
        if (isset($out['layouts/app.blade.php'])) {
            $out = ['layouts/app.blade.php' => $out['layouts/app.blade.php']] + $out;
        }

        return $out;
    }

    private function stripBlade(string $css): string
    {
        $css = preg_replace('/@php.*?@endphp/s', '', $css);
        $css = preg_replace('/\{\{.*?\}\}|\{!!.*?!!\}/s', '__BLADE__', $css);
        // Blade directives on their own (@include, @if, @endif, @yield ...), not CSS at-rules
        $css = preg_replace('/@(?!media\b|supports\b|container\b|keyframes\b|-webkit-keyframes\b|font-face\b|import\b|page\b|charset\b)[a-zA-Z]+(\s*\((?:[^()]|\([^()]*\))*\))?/', '', $css);

        return preg_replace('#/\*.*?\*/#s', '', $css);
    }

    /** Minimal CSS parser: rules and @media / @supports blocks (keyframes and font-faces are skipped) */
    private function parse(string $css): array
    {
        $i = 0;

        return $this->parseBlock($css, $i);
    }

    private function parseBlock(string $css, int &$i): array
    {
        $nodes = [];
        $len = strlen($css);
        $buf = '';
        while ($i < $len) {
            $ch = $css[$i];
            if ($ch === '}') {
                $i++;

                return $nodes;
            }
            if ($ch === ';') { // stray statement (@import, leftovers)
                $buf = '';
                $i++;
                continue;
            }
            if ($ch !== '{') {
                $buf .= $ch;
                $i++;
                continue;
            }
            $i++;
            $prelude = trim($buf);
            $buf = '';
            if (preg_match('/^@(media|supports|container)\b/i', $prelude)) {
                $nodes[] = ['at' => $prelude, 'children' => $this->parseBlock($css, $i)];
            } elseif (str_starts_with($prelude, '@')) {
                $this->skipBlock($css, $i);
            } else {
                $end = strpos($css, '}', $i);
                $end = $end === false ? $len : $end;
                $nodes[] = ['selector' => $prelude, 'decls' => substr($css, $i, $end - $i)];
                $i = $end + 1;
            }
        }

        return $nodes;
    }

    private function skipBlock(string $css, int &$i): void
    {
        $depth = 1;
        $len = strlen($css);
        while ($i < $len && $depth > 0) {
            if ($css[$i] === '{') {
                $depth++;
            } elseif ($css[$i] === '}') {
                $depth--;
            }
            $i++;
        }
    }

    /** "a:b;c:d" => [[prop, value, important], ...] (semicolons inside url(...) / quotes are kept) */
    private function declarations(string $decls): array
    {
        $out = [];
        foreach ($this->splitTop($decls, ';') as $d) {
            $pos = strpos($d, ':');
            if ($pos === false) {
                continue;
            }
            $prop = strtolower(trim(substr($d, 0, $pos)));
            $value = trim(substr($d, $pos + 1));
            $important = false;
            if (preg_match('/\s*!important\s*$/i', $value)) {
                $important = true;
                $value = trim(preg_replace('/\s*!important\s*$/i', '', $value));
            }
            if ($prop !== '' && $value !== '') {
                $out[] = [$prop, $value, $important];
            }
        }

        return $out;
    }

    private function splitTop(string $s, string $sep): array
    {
        $parts = [];
        $depth = 0;
        $quote = null;
        $cur = '';
        for ($i = 0, $n = strlen($s); $i < $n; $i++) {
            $c = $s[$i];
            if ($quote) {
                if ($c === $quote) {
                    $quote = null;
                }
            } elseif ($c === '"' || $c === "'") {
                $quote = $c;
            } elseif ($c === '(' || $c === '[') {
                $depth++;
            } elseif ($c === ')' || $c === ']') {
                $depth--;
            } elseif ($c === $sep && $depth === 0) {
                $parts[] = $cur;
                $cur = '';
                continue;
            }
            $cur .= $c;
        }
        $parts[] = $cur;

        return $parts;
    }

    private function collectVars(array $nodes): void
    {
        foreach ($nodes as $node) {
            if (isset($node['children'])) {
                $this->collectVars($node['children']);
                continue;
            }
            foreach ($this->declarations($node['decls']) as [$prop, $value]) {
                // :root wins over values set on single elements
                if (str_starts_with($prop, '--') && (!isset($this->vars[$prop]) || trim($node['selector']) === ':root')) {
                    $this->vars[$prop] = $value;
                }
            }
        }
    }

    private function resolveVars(string $value, int $depth = 0): string
    {
        if ($depth > 5 || !str_contains($value, 'var(')) {
            return $value;
        }
        $value = preg_replace_callback('/var\(\s*(--[\w-]+)\s*(?:,\s*([^()]*(?:\([^()]*\))?[^()]*))?\)/', function ($m) {
            return $this->vars[$m[1]] ?? (isset($m[2]) && $m[2] !== '' ? $m[2] : $m[0]);
        }, $value);

        return $this->resolveVars($value, $depth + 1);
    }

    /* ------------------------------------------------------------------ writing the dark rules */

    private function emit(array $nodes, string $indent = '', bool $layout = false): string
    {
        $out = '';
        foreach ($nodes as $node) {
            if (isset($node['children'])) {
                $inner = $this->emit($node['children'], $indent . '  ', $layout);
                if (trim($inner) !== '') {
                    $out .= $indent . $node['at'] . "{\n" . $inner . $indent . "}\n";
                }
                continue;
            }
            if (str_contains($node['selector'], '__BLADE__')) {
                continue;
            }
            $decls = $this->darkDeclarations($this->declarations($node['decls']));
            if ($decls) {
                $out .= $indent . $this->prefixSelector($node['selector']) . '{' . implode(';', $decls) . "}\n";
            }
            // The header line stays as in light mode: its rules are written again with their light
            // colours, a step more specific, so they win over the dark twin above
            if ($layout && ($light = $this->headerLightRule($node))) {
                $out .= $indent . $light . "\n";
            }
        }

        return $out;
    }

    /**
     * The header line that looks the same in light and dark mode: logo, menu + dropdowns, Subscription /
     * language / dark-mode buttons. (The market price strip and everything below do turn dark.)
     */
    private const HEADER_PART = '/(^|[\s>+~(])(header|nav)\b|\.(head|brand|brand-tag|brand-text|menu|menu-toggle|nav-dropdown|news-menu|media-menu|header-right|header-btn|header-subscription|lang-pill|language-select|theme-toggle)(?![\w-])/';

    private function headerLightRule(array $node): ?string
    {
        $selectors = [];
        foreach ($this->splitTop($node['selector'], ',') as $sel) {
            $sel = trim(preg_replace('/\s+/', ' ', $sel));
            if ($sel === '' || preg_match('/^(:root|html)\b/', $sel) || !preg_match(self::HEADER_PART, $sel)) {
                continue;
            }
            // ":root" makes the light copy one step stronger than its dark twin; a plain "nav" rule
            // only counts inside the header (page content can have other <nav>s, e.g. page numbers)
            $inHeaderOnly = preg_match('/(^|[\s>+~(])nav\b/', $sel) && !preg_match('/^header\b/', $sel);
            $selectors[] = self::PREFIX . ':root ' . ($inHeaderOnly ? 'header ' : '') . $sel;
        }
        if (!$selectors) {
            return null;
        }
        $decls = [];
        foreach ($this->declarations($node['decls']) as [$prop, $value, $important]) {
            if (!str_starts_with($prop, '--') && $this->role($prop) && !str_contains($value, 'url(') && !str_contains($value, '__BLADE__')) {
                $decls[] = $prop . ':' . $value . ($important ? '!important' : '');
            }
        }

        return $decls ? implode(',', $selectors) . '{' . implode(';', $decls) . '}' : null;
    }

    private function darkDeclarations(array $decls): array
    {
        // A background this rule keeps (navy panel, gold button, coloured badge): its text stays as it is
        $keepsOwnBackground = false;
        foreach ($decls as [$prop, $value]) {
            if (in_array($prop, ['background', 'background-color'], true)) {
                $resolved = $this->resolveVars($value);
                if ($this->hasOpaqueColor($resolved) && $this->recolor($resolved, 'bg') === $resolved) {
                    $keepsOwnBackground = true;
                }
            }
        }

        $out = [];
        foreach ($decls as [$prop, $value, $important]) {
            if (str_starts_with($prop, '--')) {
                continue;
            }
            $role = $this->role($prop);
            // Pictures (url(...) is relative to the page) and values filled in by Blade stay with the page
            if (!$role || str_contains($value, 'url(') || str_contains($value, '__BLADE__')) {
                continue;
            }
            if ($role === 'text' && $keepsOwnBackground) {
                $out[] = $prop . ':' . $value . ($important ? '!important' : '');
                continue;
            }
            $resolved = $this->resolveVars($value);
            $dark = str_contains($resolved, 'var(') ? $resolved : $this->recolor($resolved, $role);
            // Unchanged colours are written too: every colour rule gets the same html[data-theme] boost,
            // so a specific rule (blue button) still beats a general one (.btn-custom) like it does in light mode
            $out[] = $prop . ':' . ($dark === $resolved ? $value : $dark) . ($important ? '!important' : '');
        }

        return $out;
    }

    private function role(string $prop): ?string
    {
        return match (true) {
            in_array($prop, ['background', 'background-color', 'background-image'], true) => 'bg',
            in_array($prop, ['color', '-webkit-text-fill-color', 'caret-color', 'fill', 'stroke', 'text-decoration-color'], true) => 'text',
            (bool) preg_match('/^(border(-(top|right|bottom|left))?(-color)?|outline(-color)?|column-rule(-color)?)$/', $prop) => 'border',
            $prop === 'box-shadow' => 'shadow',
            default => null,
        };
    }

    private function prefixSelector(string $selector): string
    {
        $parts = [];
        foreach ($this->splitTop($selector, ',') as $sel) {
            $sel = trim(preg_replace('/\s+/', ' ', $sel));
            if ($sel === '') {
                continue;
            }
            if (preg_match('/^(:root|html)\b(.*)$/', $sel, $m)) {
                $parts[] = self::PREFIX . $m[2];
            } else {
                $parts[] = self::PREFIX . ' ' . $sel;
            }
        }

        return implode(',', $parts);
    }

    private const COLOR_RE = '/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)|\b(?<![-\w])(white|black)\b(?![-\w])/';

    private function hasOpaqueColor(string $value): bool
    {
        if (!preg_match_all(self::COLOR_RE, $value, $m)) {
            return false;
        }
        foreach ($m[0] as $c) {
            $rgba = $this->parseColor($c);
            if ($rgba && $rgba[3] >= 0.5) {
                return true;
            }
        }

        return false;
    }

    private function recolor(string $value, string $role): string
    {
        return preg_replace_callback(self::COLOR_RE, function ($m) use ($role) {
            $rgba = $this->parseColor($m[0]);
            if (!$rgba) {
                return $m[0];
            }
            $new = $this->transform($rgba, $role);

            return $new === null ? $m[0] : $this->formatColor($new);
        }, $value);
    }

    /** [r,g,b,a] => new [r,g,b,a], or null when the colour already suits a dark page */
    private function transform(array $rgba, string $role): ?array
    {
        [$r, $g, $b, $a] = $rgba;
        [$h, $s, $l] = $this->rgbToHsl($r, $g, $b);
        $grey = $s < 0.06;

        switch ($role) {
            case 'bg':
            case 'shadow':
                if ($a < 0.25) {
                    return null; // faint overlays (white glass on navy panels, soft tints) work on both
                }
                if ($l >= 0.8) {
                    // white / pale tint -> dark navy surface (white cards a touch lighter than the page)
                    [$h2, $s2] = $grey ? [228, 0.30] : [$h, min($s, 0.45)];

                    return [...$this->hslToRgb($h2, $s2, max(0.07, 0.16 - (1 - $l) * 0.8)), $a];
                }
                if ($role === 'bg' && $l >= 0.6 && $s < 0.25) {
                    return [...$this->hslToRgb($grey ? 228 : $h, min($s, 0.2), 0.30), $a]; // light grey
                }

                return null;

            case 'text':
                if ($l > 0.55) {
                    return null; // already light enough
                }
                // dark text -> light: navy / grey body text becomes soft white, coloured text (red,
                // green, blue links) keeps its colour, just lighter
                $ink = $s < 0.35 || ($h >= 200 && $h <= 250 && $l < 0.3);
                if ($ink) {
                    return [...$this->hslToRgb($h, min($s, 0.25), 0.92 - $l * 0.42), $a];
                }

                return [...$this->hslToRgb($h, min($s, 0.75), 0.66 + $l * 0.1), $a];

            case 'border':
                if ($a < 0.5 || $l < 0.75) {
                    return null;
                }

                return [...$this->hslToRgb($grey ? 228 : $h, min($s, 0.3), 0.25), $a];
        }

        return null;
    }

    private function parseColor(string $c): ?array
    {
        $c = strtolower(trim($c));
        if ($c === 'white') {
            return [255, 255, 255, 1.0];
        }
        if ($c === 'black') {
            return [0, 0, 0, 1.0];
        }
        if ($c[0] === '#') {
            $hex = substr($c, 1);
            if (strlen($hex) === 3 || strlen($hex) === 4) {
                $hex = implode('', array_map(fn ($ch) => $ch . $ch, str_split($hex)));
            }
            if (strlen($hex) !== 6 && strlen($hex) !== 8) {
                return null;
            }
            $a = strlen($hex) === 8 ? hexdec(substr($hex, 6, 2)) / 255 : 1.0;

            return [hexdec(substr($hex, 0, 2)), hexdec(substr($hex, 2, 2)), hexdec(substr($hex, 4, 2)), $a];
        }
        if (preg_match('/^rgba?\(([^)]*)\)$/', $c, $m)) {
            $p = preg_split('/[\s,\/]+/', trim($m[1]));
            if (count($p) < 3 || str_contains($m[1], 'var(')) {
                return null;
            }
            $num = fn ($v) => str_ends_with($v, '%') ? (float) $v * 2.55 : (float) $v;
            $a = isset($p[3]) ? (str_ends_with($p[3], '%') ? (float) $p[3] / 100 : (float) $p[3]) : 1.0;

            return [$num($p[0]), $num($p[1]), $num($p[2]), $a];
        }
        if (preg_match('/^hsla?\(([^)]*)\)$/', $c, $m)) {
            $p = preg_split('/[\s,\/]+/', trim($m[1]));
            if (count($p) < 3) {
                return null;
            }
            $a = isset($p[3]) ? (str_ends_with($p[3], '%') ? (float) $p[3] / 100 : (float) $p[3]) : 1.0;

            return [...$this->hslToRgb((float) $p[0], (float) $p[1] / 100, (float) $p[2] / 100), $a];
        }

        return null;
    }

    private function formatColor(array $rgba): string
    {
        [$r, $g, $b, $a] = array_map(fn ($v) => $v, $rgba);
        $r = (int) round($r);
        $g = (int) round($g);
        $b = (int) round($b);
        if ($a >= 0.999) {
            return sprintf('#%02x%02x%02x', $r, $g, $b);
        }

        return sprintf('rgba(%d,%d,%d,%s)', $r, $g, $b, rtrim(rtrim(number_format($a, 3, '.', ''), '0'), '.'));
    }

    private function rgbToHsl(float $r, float $g, float $b): array
    {
        $r /= 255;
        $g /= 255;
        $b /= 255;
        $max = max($r, $g, $b);
        $min = min($r, $g, $b);
        $l = ($max + $min) / 2;
        if ($max === $min) {
            return [0, 0, $l];
        }
        $d = $max - $min;
        $s = $l > 0.5 ? $d / (2 - $max - $min) : $d / ($max + $min);
        $h = match ($max) {
            $r => ($g - $b) / $d + ($g < $b ? 6 : 0),
            $g => ($b - $r) / $d + 2,
            default => ($r - $g) / $d + 4,
        };

        return [$h * 60, $s, $l];
    }

    private function hslToRgb(float $h, float $s, float $l): array
    {
        $h = fmod(fmod($h, 360) + 360, 360) / 360;
        if ($s == 0) {
            return [$l * 255, $l * 255, $l * 255];
        }
        $q = $l < 0.5 ? $l * (1 + $s) : $l + $s - $l * $s;
        $p = 2 * $l - $q;
        $hue = function ($t) use ($p, $q) {
            if ($t < 0) {
                $t += 1;
            }
            if ($t > 1) {
                $t -= 1;
            }

            return match (true) {
                $t < 1 / 6 => $p + ($q - $p) * 6 * $t,
                $t < 1 / 2 => $q,
                $t < 2 / 3 => $p + ($q - $p) * (2 / 3 - $t) * 6,
                default => $p,
            };
        };

        return [$hue($h + 1 / 3) * 255, $hue($h) * 255, $hue($h - 1 / 3) * 255];
    }

    /* ------------------------------------------------------------------ hand-made part */

    /** Things the colour rules can't work out on their own */
    private function manual(): string
    {
        return <<<'CSS'

/* ---- Hand-made dark-mode fixes ---- */
html[data-theme="dark"]{color-scheme:dark}
html[data-theme="dark"] body{scrollbar-color:#3a4366 #10152a}
/* The header line keeps its light look in dark mode (see headerLightRule): light form controls and
   text for anything in it that has no colour of its own */
html[data-theme="dark"]:root header{color-scheme:light;color:#141f3d}
/* Bootstrap helpers that stay light in its own dark theme */
html[data-theme="dark"] .bg-white,html[data-theme="dark"] .bg-light{background-color:#1c2135!important}
html[data-theme="dark"] .text-dark{color:#e4e7f1!important}
html[data-theme="dark"] .text-muted{color:#a3abc2!important}
/* Colours written in style="..." attributes on the pages */
html[data-theme="dark"] [style*="color:var(--blue)"],html[data-theme="dark"] [style*="color:#2b3f9e"]{color:#9da9e4!important}
html[data-theme="dark"] [style*="color:var(--navy)"],html[data-theme="dark"] [style*="color:#141f55"]{color:#d0d5e3!important}
html[data-theme="dark"] [style*="color:var(--muted)"]{color:#afb7c6!important}
/* Article text pasted from editors with its own black / white colours */
html[data-theme="dark"] .np-content [style*="color"]{color:inherit!important}
html[data-theme="dark"] .np-content [style*="background"]{background:transparent!important}
CSS;
    }
}
